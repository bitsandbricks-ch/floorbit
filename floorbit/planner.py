BUILTIN = {
    'cisco-ios': {'label': 'Cisco IOS (Catalyst)', 'access': 'GigabitEthernet1/0/{n}',
                  'uplink': 'GigabitEthernet1/1/{u}', 'text': CISCO_IOS},
    'aruba-cx': {'label': 'Aruba AOS-CX', 'access': '1/1/{n}', 'uplink': '1/1/{u}', 'text': ARUBA_CX},
}

_lock = threading.Lock()
_ID = re.compile(r'^[a-z0-9][a-z0-9-]{0,39}$')


class PlannerError(ValueError):
    def __init__(self, message, status=400):
        super().__init__(message)
        self.status = status


# ── Settings and templates ──────────────────────────────────────────────────────────────
def _stored(data):
    raw = data.get(KEY)
    return raw if isinstance(raw, dict) else {}


def settings(data=None):
    data = data if data is not None else load_data()
    saved = _stored(data).get('settings') or {}
    return {**DEFAULTS, **{k: v for k, v in saved.items() if k in DEFAULTS}}


def templates(data=None):
    """Built-in models, then custom ones (a custom one with a built-in's id replaces it)."""
    data = data if data is not None else load_data()
    out = {k: {**v, 'id': k, 'builtin': True} for k, v in BUILTIN.items()}
    for k, v in (_stored(data).get('templates') or {}).items():
        if isinstance(v, dict) and _ID.match(k):
            out[k] = {**v, 'id': k, 'builtin': False}
    return out


def _int(body, key, lo, hi):
    try:
        value = int(body[key])
    except (TypeError, ValueError):
        raise PlannerError(f'{key.replace("_", " ").capitalize()} must be a whole number.') from None
    if not lo <= value <= hi:
        raise PlannerError(f'{key.replace("_", " ").capitalize()} must be between {lo} and {hi}.')
    return value


def clean_settings(body, data):
    out = settings(data)
    for key, lo, hi in (('access_ports', 4, 96), ('uplink_ports', 0, 8), ('spare', 0, 24), ('vlan_base', 2, 4000),
                        ('mgmt_first', 1, 65000), ('mgmt_vlan', 1, 4094)):
        if key in body:
            out[key] = _int(body, key, lo, hi)
    if out['spare'] >= out['access_ports']:
        raise PlannerError('Keep fewer spare ports than the switch has.')
    if 'vlan_mode' in body:
        if body['vlan_mode'] not in VLAN_MODES:
            raise PlannerError(f"VLAN mode must be one of: {', '.join(VLAN_MODES)}.")
        out['vlan_mode'] = body['vlan_mode']
    if 'model' in body:
        if body['model'] not in templates(data):
            raise PlannerError('No such switch model.')
        out['model'] = body['model']
    if 'name' in body:
        name = str(body['name'] or '').strip()[:60]
        try:
            name.format(block='a', n=1, hall='main')
        except (KeyError, IndexError, ValueError):
            raise PlannerError('The name pattern may use {block}, {hall} and {n}, e.g. sw-{block}-{n:02d}.') from None
        if not name or '{n' not in name:
            raise PlannerError('The name pattern needs {n}, so switches in one block get different names.')
        out['name'] = name
    if 'mgmt_net' in body:
        net = str(body['mgmt_net'] or '').strip()
        if net:
            try:
                net = str(ipaddress.ip_network(net, strict=False))
            except ValueError:
                raise PlannerError('The management network must look like 10.10.0.0/24.') from None
        out['mgmt_net'] = net
    if 'mgmt_gateway' in body:
        gw = str(body['mgmt_gateway'] or '').strip()
        if gw:
            try:
                gw = str(ipaddress.ip_address(gw))
            except ValueError:
                raise PlannerError('The gateway must be an IP address.') from None
        out['mgmt_gateway'] = gw
    return out


def save_settings(body):
    with _lock:
        data = load_data()
        cleaned = clean_settings(body, data)
        data[KEY] = {**_stored(data), 'settings': cleaned}
        save_data(data)
        return cleaned


def save_template(template_id, body):
    if not _ID.match(template_id or ''):
        raise PlannerError('Template ids are lower case letters, digits and dashes.')
    text = str(body.get('text') or '')
    if not text.strip() or len(text) > MAX_TEMPLATE:
        raise PlannerError(f'The template must have text, at most {MAX_TEMPLATE} characters.')
    access, uplink = str(body.get('access') or ''), str(body.get('uplink') or '')
    if '{n}' not in access or ('{n}' not in uplink and '{u}' not in uplink):
        raise PlannerError('Port names need {n}, e.g. GigabitEthernet1/0/{n}; uplinks may use {u} instead.')
    _compile(text)
    item = {'label': str(body.get('label') or template_id).strip()[:60], 'access': access[:60], 'uplink': uplink[:60],
            'text': text}
    with _lock:
        data = load_data()
        stored = _stored(data)
        data[KEY] = {**stored, 'templates': {**(stored.get('templates') or {}), template_id: item}}
        save_data(data)
    return {**item, 'id': template_id, 'builtin': False}


def delete_template(template_id):
    with _lock:
        data = load_data()
        stored = _stored(data)
        custom = dict(stored.get('templates') or {})
        if template_id not in custom:
            raise PlannerError('Only custom templates can be removed.', 404)
        custom.pop(template_id)
        data[KEY] = {**stored, 'templates': custom}
        if settings(data)['model'] == template_id:
            data[KEY]['settings'] = {**settings(data), 'model': 'cisco-ios'}
        save_data(data)


# ── The plan ────────────────────────────────────────────────────────────────────────────
def _port_name(pattern, n, u=None):
    return pattern.replace('{n}', str(n)).replace('{u}', str(u if u is not None else n))


def build(data=None, cfg=None):
    """Switches per block, the seat on each port, VLANs and management IPs."""
    from . import halls
    from .power import block_rows
    data = data if data is not None else load_data()
    cfg = cfg or settings(data)
    model = templates(data).get(cfg['model']) or templates(data)['cisco-ios']
    hall_names = {h['id']: h['name'] for h in halls.halls(data)}
    usable = cfg['access_ports'] - cfg['spare']
    existing = {str(d.get('name') or '').lower() for d in data.get('inventory') or []}
    net = ipaddress.ip_network(cfg['mgmt_net']) if cfg['mgmt_net'] else None
    blocks, switches, vlans = [], [], {}
    for block in sorted((b for b in data.get('seat_blocks') or [] if b.get('name')),
                        key=lambda b: (str(b.get('hall_id') or ''), str(b['name']).upper())):
        name = str(block['name']).upper()
        hall = block.get('hall_id') or 'main'
        seats = [s for row in block_rows(block) for s in row]
        if not seats:
            continue
        key = {'block': f'block {name}', 'hall': f'hall {hall}', 'one': 'seats'}[cfg['vlan_mode']]
        if key not in vlans:
            vlans[key] = {'id': cfg['vlan_base'] + len(vlans), 'name': re.sub(r'[^A-Za-z0-9-]+', '-', key)[:32]}
        vlan = vlans[key]
        count = -(-len(seats) // usable)
        names = []
        for i in range(count):
            chunk = seats[i * usable:(i + 1) * usable]
            sw_name = cfg['name'].format(block=name.lower(), hall=hall, n=i + 1)
            ports = [{'n': n + 1, 'name': _port_name(model['access'], n + 1), 'seat': seat, 'vlan': vlan['id']}
                     for n, seat in enumerate(chunk)]
            spare = [{'n': n, 'name': _port_name(model['access'], n)}
                     for n in range(len(chunk) + 1, cfg['access_ports'] + 1)]
            uplinks = [{'n': u, 'name': _port_name(model['uplink'], cfg['access_ports'] + u, u)}
                       for u in range(1, cfg['uplink_ports'] + 1)]
            switches.append({'name': sw_name, 'block': name, 'hall_id': hall, 'hall': hall_names.get(hall, hall),
                             'vlan': vlan['id'], 'vlans': [vlan], 'ports': ports, 'spare': spare,
                             'uplinks': uplinks, 'mgmt_ip': None, 'exists': sw_name.lower() in existing,
                             'x': float(block.get('x') or 0) - 40, 'y': float(block.get('y') or 0) + 40 * i})
            names.append(sw_name)
        blocks.append({'name': name, 'hall': hall_names.get(hall, hall), 'seats': len(seats), 'vlan': vlan['id'],
                       'switches': names})
    if len(switches) > MAX_SWITCHES:
        raise PlannerError(f'The plan would need more than {MAX_SWITCHES} switches. Check the port counts.')
    mgmt = {'vlan': cfg['mgmt_vlan'], 'gateway': cfg['mgmt_gateway'], 'netmask': '', 'prefix': ''}
    problems = []
    if net is not None:
        mgmt.update(netmask=str(net.netmask), prefix=net.prefixlen)
        hosts = list(net.hosts()) if net.num_addresses <= 65536 else []
        taken = {cfg['mgmt_gateway']}
        pool = [str(h) for h in hosts[max(cfg['mgmt_first'] - 1, 0):] if str(h) not in taken]
        for sw, ip in zip(switches, pool, strict=False):
            sw['mgmt_ip'] = ip
        if len(pool) < len(switches):
            problems.append(f'The management network has room for {len(pool)} switches, the plan needs '
                            f'{len(switches)}.')
    return {'settings': cfg, 'model': {k: model[k] for k in ('id', 'label', 'access', 'uplink')},
            'blocks': blocks, 'switches': switches, 'vlans': sorted(vlans.values(), key=lambda v: v['id']),
            'mgmt': mgmt, 'problems': problems,
            'totals': {'seats': sum(b['seats'] for b in blocks), 'switches': len(switches),
                       'new': sum(not s['exists'] for s in switches), 'vlans': len(vlans),
                       'uplinks': len(switches) * cfg['uplink_ports']}}


# ── Configs ─────────────────────────────────────────────────────────────────────────────
_env = SandboxedEnvironment(undefined=StrictUndefined, autoescape=False, keep_trailing_newline=True)


def _compile(text):
    try:
        return _env.from_string(text)
    except TemplateError as exc:
        raise PlannerError(f'The template does not compile: {exc}') from None


def render(plan, switch, data=None, event_name=''):
    model = templates(data).get(plan['model']['id']) or templates(data)['cisco-ios']
    try:
        return _compile(model['text']).render(switch=switch, mgmt=plan['mgmt'], vlans=plan['vlans'],
                                              event={'name': event_name})
    except TemplateError as exc:
        raise PlannerError(f"The template failed for {switch['name']}: {exc}") from None


def configs_zip(plan, data=None, event_name=''):
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, 'w', zipfile.ZIP_DEFLATED) as z:
        for sw in plan['switches']:
            z.writestr(f"{sw['name']}.cfg", render(plan, sw, data, event_name))
        z.writestr('plan.csv', plan_csv(plan))
    return buf.getvalue()


def plan_csv(plan):
    lines = ['switch,port,seat,vlan,block,hall,mgmt_ip']
    for sw in plan['switches']:
        for p in sw['ports']:
            lines.append(','.join(_csv(v) for v in (sw['name'], p['name'], p['seat'], p['vlan'], sw['block'],
                                                    sw['hall'], sw['mgmt_ip'] or '')))
    return '\n'.join(lines) + '\n'


def _csv(value):
    text = str(value)
    if text[:1] in ('=', '+', '-', '@'):
        text = "'" + text   # never a formula in a spreadsheet
    return f'"{text}"' if any(c in text for c in ',"\n') else text


# ── Labels ──────────────────────────────────────────────────────────────────────────────
LABEL_COLS, LABEL_ROWS = 3, 10
MARGIN_X, MARGIN_Y = 20.0, 36.0


def labels_pdf(plan, copies=2, block=None):
    """Cable labels on A4, 3 x 10 per page: the seat big, the switch and port small. ``copies``
    labels per cable (one for each end)."""
    items = [(p['seat'], f"{sw['name']} {p['name']}") for sw in plan['switches']
             if not block or sw['block'] == block for p in sw['ports']]
    items = [i for i in items for _ in range(max(1, min(int(copies), 4)))]
    w = (pdf.A4[0] - 2 * MARGIN_X) / LABEL_COLS
    h = (pdf.A4[1] - 2 * MARGIN_Y) / LABEL_ROWS
    pages = []
    per_page = LABEL_COLS * LABEL_ROWS
    for start in range(0, max(len(items), 1), per_page):
        page = pdf.Page()
        for k, (seat, where) in enumerate(items[start:start + per_page]):
            x = MARGIN_X + (k % LABEL_COLS) * w
            y = MARGIN_Y + (k // LABEL_COLS) * h
            page.rect(x + 3, y + 3, w - 6, h - 6, stroke='#c9ced6')
            page.text(x + w / 2, y + h / 2 - 2, seat, size=22, bold=True, align='center')
            page.text(x + w / 2, y + h / 2 + 18, pdf.fit(where, 8, w - 14), size=8, color='#5b6370', align='center')
        pages.append(page)
    return pdf.render(pages, title='Cable labels')


# ── Applying the plan ───────────────────────────────────────────────────────────────────
def add_switches(plan):
    """Create the planned switches that don't exist yet, next to their blocks. Returns their names."""
    from . import inventory
    from .blueprints.inventory import data_lock
    added = []
    with data_lock:
        data = load_data()
        names = {str(d.get('name') or '').lower() for d in inventory.devices(data, include_hidden=True)}
        for sw in plan['switches']:
            if sw['name'].lower() in names:
                continue
            dev = inventory.create(data, {'name': sw['name'], 'role': 'switch', 'model': plan['model']['label'],
                                          'mgmt_ip': sw['mgmt_ip'] or '', 'status': 'planned',
                                          'x': sw['x'], 'y': sw['y']})
            dev['hall_id'] = sw['hall_id']
            names.add(sw['name'].lower())
            added.append(sw['name'])
        if added:
            save_data(data)
    return added
