"""Build planner (issue #34): switches, ports and VLANs per seat block, configs and labels. See docs/planner.md.

From the seat blocks on the floor plan, the planner suggests how many access switches each block
needs, which port each seat gets, a VLAN per block (or per hall, or one for all) and a management IP
per switch. From that plan it renders one config per switch from a Jinja template per switch model,
and printable cable labels (seat end and switch end).

- Templates run in Jinja's sandbox: leads edit them, and a template must not reach into Python.
- Interface descriptions are ``Seat A-12``, the form the needs-attention watch, port actions and
  QoS hints read (``attention.seat_of``), so a switch built from the plan works with the rest of
  Floorbit without more setup.
- "Add switches to the floor plan" creates the switches that don't exist yet (same name), placed
  next to their block, as ``planned`` devices with the model and management IP.

Settings and custom templates live in data.json under ``planner``.
"""
import io
import ipaddress
import re
import threading
import zipfile

from jinja2 import StrictUndefined, TemplateError
from jinja2.sandbox import SandboxedEnvironment

from . import pdf
from .store import load_data, save_data

KEY = 'planner'
MAX_TEMPLATE = 50_000
MAX_SWITCHES = 500
VLAN_MODES = ('block', 'hall', 'one')
DEFAULTS = {
    'model': 'cisco-ios',
    'access_ports': 48,      # copper ports per switch
    'uplink_ports': 2,       # uplink (SFP) ports per switch, numbered on their own
    'spare': 2,              # access ports kept free on each switch for staff, a stream PC or a swap
    'vlan_mode': 'block',
    'vlan_base': 100,
    'name': 'sw-{block}-{n:02d}',
    'mgmt_net': '',          # e.g. 10.10.0.0/24: switches get addresses from mgmt_first on
    'mgmt_first': 11,
    'mgmt_gateway': '',
    'mgmt_vlan': 10,
}

